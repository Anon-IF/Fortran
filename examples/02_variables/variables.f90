! ============================================================
! 文件名：variables.f90
! 功  能：演示 Fortran 中的基本数据类型与变量声明
! 对应教材：工程分析程序设计 第2章
!
! 编译命令：gfortran variables.f90 -o variables
! 运行命令：./variables
! ============================================================

program variables
  implicit none

  ! ── 整数类型 ──────────────────────────────────────────────
  integer :: age           ! 声明一个整数变量，名为 age
  integer :: count = 0     ! 声明并赋初值

  ! ── 实数（浮点数）类型 ────────────────────────────────────
  real :: height           ! 单精度浮点数（约6-7位有效数字）
  real(8) :: pi            ! 双精度浮点数（约15-16位有效数字），推荐科学计算使用

  ! ── 字符类型 ──────────────────────────────────────────────
  character(len=20) :: name   ! 最多存储 20 个字符的字符串

  ! ── 逻辑类型 ──────────────────────────────────────────────
  logical :: is_student    ! 逻辑变量，只能是 .true. 或 .false.

  ! ── 给变量赋值 ────────────────────────────────────────────
  age        = 20
  height     = 1.75
  pi         = 3.141592653589793_8   ! _8 表示双精度常数
  name       = "张三"
  is_student = .true.

  ! ── 输出变量值 ────────────────────────────────────────────
  print *, "姓名：", name
  print *, "年龄：", age
  print *, "身高：", height, "米"
  print *, "圆周率（双精度）：", pi
  print *, "是否为学生：", is_student

  ! ── 算术运算 ──────────────────────────────────────────────
  print *, ""
  print *, "=== 算术运算示例 ==="
  print *, "5 + 3 =", 5 + 3           ! 加法
  print *, "10 - 4 =", 10 - 4         ! 减法
  print *, "3 * 7 =", 3 * 7           ! 乘法
  print *, "10 / 3 =", 10 / 3         ! 整数除法，结果为 3（截断小数部分！）
  print *, "10.0 / 3.0 =", 10.0 / 3.0 ! 实数除法，结果为 3.333...
  print *, "2 ** 10 =", 2 ** 10       ! 幂运算：2 的 10 次方

  ! 注意：整数除整数结果还是整数！这是初学者常见的错误来源
  count = 7 / 2
  print *, ""
  print *, "注意：7 / 2 在整数运算中 =", count, "（不是 3.5！）"
  print *, "    : 7.0 / 2.0 =", 7.0 / 2.0, "（需要用实数相除）"

end program variables
