! ============================================================
! 文件：basic_io.f90
! 功能：演示基本输入 / 输出操作
! 对应教材：第1章  Fortran 程序设计基础
! ============================================================
!
! 知识点：
!   • print *   ——向屏幕输出（* 表示"默认格式"）
!   • read  *   ——从键盘读取
!   • write(*,*)——与 print * 等价的另一种写法
!   • 字符串用双引号 " " 括起来
!
program basic_io
  implicit none

  ! ---------- 变量声明 ----------
  integer :: age         ! 整数变量：存放年龄
  real    :: height      ! 单精度实数：存放身高（米）
  character(len=20) :: name  ! 字符串变量：最多 20 个字符

  ! ---------- 输出提示信息 ----------
  print *, "==============================="
  print *, "   基本输入输出示例"
  print *, "==============================="

  ! ---------- 读取用户输入 ----------
  write(*, *) "请输入您的姓名（不超过20个字符）："
  read(*, *)  name

  write(*, *) "请输入您的年龄（整数）："
  read(*, *)  age

  write(*, *) "请输入您的身高（单位：米，如 1.75）："
  read(*, *)  height

  ! ---------- 输出结果 ----------
  print *, "------- 您输入的信息 -------"
  print *, "姓名：", trim(name)   ! trim() 去掉字符串末尾的空格
  print *, "年龄：", age, " 岁"
  print *, "身高：", height, " 米"

end program basic_io
