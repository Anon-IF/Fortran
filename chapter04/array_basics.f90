! ============================================================
! 文件：array_basics.f90
! 功能：演示数组的声明、初始化、访问和基本操作
! 对应教材：第5章  数组
! ============================================================
!
! 关键概念：
!   • Fortran 数组下标默认从 1 开始（与 C/Python 不同！）
!   • 一维数组：向量
!   • 二维数组：矩阵
!   • 数组可以整体赋值和整体运算（向量化操作）
!
program array_basics
  implicit none

  integer :: i, j

  ! ---------- 一维数组 ----------
  real(8) :: a(5)              ! 声明方式1：直接在名字后加维度
  real(8), dimension(5) :: b  ! 声明方式2：用 dimension 属性（等价）

  ! ---------- 二维数组（矩阵）----------
  real(8) :: mat(3, 3)   ! 3行3列矩阵；mat(行, 列)

  ! ===== 一维数组初始化 =====
  ! 方式1：逐元素赋值
  a(1) = 1.0_8
  a(2) = 4.0_8
  a(3) = 9.0_8
  a(4) = 16.0_8
  a(5) = 25.0_8

  ! 方式2：数组构造器
  b = (/ 2.0_8, 4.0_8, 6.0_8, 8.0_8, 10.0_8 /)
  ! Fortran 2003+ 也可用方括号：b = [2.0_8, 4.0_8, 6.0_8, 8.0_8, 10.0_8]

  ! 方式3：隐式 do 循环构造器（生成 1,2,3,4,5）
  ! integer :: c(5) = [(i, i=1, 5)]   ! 仅整数示例

  print *, "===== 一维数组 ====="
  print *, "a =", a
  print *, "b =", b
  print *, "a(3) =", a(3)   ! 访问第3个元素

  ! ===== 整体运算（向量化）=====
  print *, "===== 数组整体运算 ====="
  print *, "a + b =", a + b         ! 对应元素相加
  print *, "a * b =", a * b         ! 对应元素相乘（非矩阵乘法！）
  print *, "a * 2 =", a * 2         ! 每个元素乘以 2
  print *, "sqrt(a) =", sqrt(a)     ! 对每个元素求平方根

  ! ===== 内置数组函数 =====
  print *, "===== 数组内置函数 ====="
  print *, "sum(a)    =", sum(a)          ! 所有元素求和
  print *, "maxval(a) =", maxval(a)       ! 最大值
  print *, "minval(a) =", minval(a)       ! 最小值
  print *, "size(a)   =", size(a)         ! 元素总数
  print *, "maxloc(a) =", maxloc(a)       ! 最大值所在下标

  ! ===== 数组切片 =====
  print *, "===== 数组切片 ====="
  print *, "a(2:4) =", a(2:4)          ! 第2到第4个元素（共3个）
  print *, "a(1:5:2) =", a(1:5:2)      ! 步长为2：a(1), a(3), a(5)

  ! ===== 二维数组（矩阵）=====
  print *, "===== 二维数组 ====="
  ! 初始化为单位矩阵（对角线为1，其余为0）
  mat = 0.0_8
  do i = 1, 3
    mat(i, i) = 1.0_8   ! 对角线元素
  end do

  ! 打印矩阵（按行输出）
  print *, "单位矩阵："
  do i = 1, 3
    print "(3f8.3)", (mat(i, j), j=1, 3)   ! 格式化输出一行
  end do

  ! Fortran 存储数组按"列优先"（column-major）——与 C 的行优先相反！
  print *, "注意：Fortran 二维数组按列优先存储！"

end program array_basics
