! ============================================================
! 文件：formatted_io.f90
! 功能：演示格式化输入输出
! 对应教材：第7章  文件操作 / 格式化 I/O
! ============================================================
!
! Fortran 的格式化 I/O 通过"格式描述符"控制输出的宽度、精度、对齐方式。
!
! 常用格式描述符：
!   I w        整数，占 w 个字符宽度
!   F w.d      浮点数，总宽 w，小数 d 位
!   E w.d      科学计数法，总宽 w，小数 d 位
!   A w        字符串，占 w 个字符宽度
!   X          输出一个空格
!   /          换行
!   nX         输出 n 个空格
!   (重复)      n次描述符可写成 nFw.d，如 3F8.3
!
program formatted_io
  implicit none

  integer :: i
  real(8) :: x
  real(8) :: data(5)

  data = [1.0_8, 2.5_8, 100.333_8, -7.8_8, 0.001_8]

  ! ===== 整数格式 =====
  print *, "===== 整数格式 I ====="
  do i = 1, 5
    write(*, "(i5)") i * 100     ! 占5字符宽，右对齐
  end do

  ! ===== 实数格式 F =====
  print *, "===== 浮点格式 F ====="
  do i = 1, 5
    write(*, "(f10.3)") data(i)  ! 总宽10，小数3位
  end do

  ! ===== 科学计数法 E =====
  print *, "===== 科学计数法 E ====="
  do i = 1, 5
    write(*, "(e14.5)") data(i)  ! 总宽14，小数5位
  end do

  ! ===== 混合格式 =====
  print *, "===== 混合格式 ====="
  print *, "  序号    数值         平方"
  print *, repeat("-", 35)
  do i = 1, 5
    write(*, "(i4, 2x, f10.4, 2x, e14.6)") i, data(i), data(i)**2
    !           ^整数  ^空格  ^实数  ^空格  ^科学计数
  end do

  ! ===== 字符串格式 =====
  print *, "===== 字符串格式 A ====="
  write(*, "(a20, f8.2)") "圆周率 PI ≈", acos(-1.0_8)

  ! ===== 输出到字符串（内部写入）=====
  print *, "===== 内部写入（write to string）====="
  block
    character(len=50) :: str
    x = 3.14159_8
    write(str, "(a, f6.4)") "π = ", x   ! 写入字符串而非屏幕
    print *, trim(str)
  end block

end program formatted_io
